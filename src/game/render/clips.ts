/**
 * Покадровые клипы. Трек: [время 0..1, значение]; null = «текущая базовая поза класса».
 * Для ADD-ключей значение прибавляется к базовой позе (корпус, ноги, голова),
 * для остальных (руки, кисти, пальцы) — абсолютное.
 * Рука: shRx<0 — вперёд/вверх, shRz<0 — правая рука в сторону; elR<0 — сгиб локтя;
 * wrRx>0 — оружие наклоняется вперёд по линии руки; fcR — сжатие пальцев 0..1.
 */
export type K = [number, number | null][];
export interface Clip {
  dur: number; impact: number; keys: Record<string, K>;
  face?: Emotion; useL?: boolean; hold?: [number, number]; // hold — окно, где поза удерживается (канал)
}
export const ADD_KEYS = new Set(["spineX", "spineY", "spineZ", "headX", "headY", "hipsY", "hipRx", "hipLx", "kneeR", "kneeL", "hipRz", "hipLz", "rootZ", "rootX", "rootY", "bodyRy", "neckX", "hipsRy"]);

const osc = (n: number, a: number | null, b: number, t0 = 0.1, t1 = 0.9): K => {
  const k: K = [[0, a]];
  for (let i = 0; i < n * 2; i++) k.push([t0 + ((t1 - t0) * (i + 0.5)) / (n * 2), i % 2 ? a ?? 0 : b]);
  k.push([1, a]);
  return k;
};

