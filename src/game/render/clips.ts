/** Какое лицо изображать в базовых (старых) действиях */
export const ACTION_FACE: Record<string, Emotion> = {
  slash: "angry", slash2: "angry", stab: "focus", cast: "focus", shoot: "focus", bash: "angry", whip: "smug", spin: "roar", leap: "roar",
  buff: "focus", heal: "happy", hit: "pain", block: "angry",
};

export interface AnimSpec { kind: string; dur: number; impact: number }

const IMPACT_OLD: Record<string, [number, number]> = {
  slash: [0.8, 0.48], slash2: [0.8, 0.5], stab: [0.65, 0.4], cast: [0.8, 0.55], shoot: [0.9, 0.6], bash: [0.8, 0.45], whip: [0.8, 0.45], spin: [0.9, 0.5], leap: [0.9, 0.55],
  buff: [0.9, 0.5], heal: [0.9, 0.5], hit: [0.4, 0.15], block: [0.5, 0.3],
};

export function animInfo(kind: string, dur?: number): AnimSpec {
  const c = CLIPS[kind];
  if (c) return { kind, dur: dur ?? c.dur, impact: c.impact };
  const o = IMPACT_OLD[kind] ?? [0.8, 0.5];
  return { kind, dur: dur ?? o[0], impact: o[1] };
}

/**
 * Подбор уникальной анимации под каждое умение: класс + тип + эффект + число ударов + название.
 * Не изменяет игровые тайминги: возвращает только визуальную длительность и момент попадания.
 */
export function animForSkill(s: SkillDef): AnimSpec {
  const cls: ClassId = s.cls;
  const v = s.vfx, kind = s.kind ?? "tgt";
  const hits = s.hits ?? 1;
  const nm = s.name.toLowerCase();
  let k = "slash";
  const melee = cls === "warrior" || cls === "assassin" || cls === "shieldbearer" || cls === "berserker";
  switch (kind) {
    case "tgt":
      if (hits >= 3) k = melee ? "flurry" : cls === "archer" ? "volley" : "channel";
      else if (v === "arrow") k = "shoot";
      else if (v === "bolt") k = /бур|шторм|молн|цеп/.test(nm) ? "channel" : "cast";
      else if (v === "beam") k = "channel";
      else if (v === "whip") k = "whip";
      else if (v === "stab") k = s.stun || s.dot ? "backstab" : "stab";
      else if (v === "bash") k = s.stun ? "shieldbash" : "bash";
      else if (v === "cleave") k = s.power >= 2 ? "overhead" : "slash";
      else if (cls === "warrior") k = s.power >= 2.8 || /казн|сокруш/.test(nm) ? "overhead" : s.stun ? "uppercut" : s.dot ? "thrust" : "slash";
      else if (cls === "assassin") k = "thrust";
      else if (cls === "tamer") k = "command";
      else k = "cast";
      break;
    case "aoe":
      k = v === "whirl" || v === "cleave" ? "spin" : v === "quake" ? "slam" : v === "nova" || v === "bolt" || v === "beam" ? "nova" : v === "rain" ? (cls === "archer" ? "skyshot" : "skycall") : v === "pillar" ? "skycall" : v === "stab" ? "backstab" : "nova";
      if (cls === "archer" && v === "nova") k = "volley";
      break;
    case "aoet":
      k = v === "rain" ? (cls === "archer" ? "skyshot" : "skycall") : v === "quake" ? "slam" : v === "nova" ? "nova" : v === "arrow" ? "skyshot" : "skycall";
      break;
    case "dash": k = cls === "mage" || cls === "sorcerer" || cls === "archer" ? "roll" : cls === "assassin" ? "backstab" : "dashstrike"; break;
    case "heal": k = "bless"; break;
    case "shield": k = cls === "shieldbearer" ? "guard" : "ward"; break;
    case "buff": k = cls === "warrior" ? "warcry" : cls === "berserker" ? "roar" : cls === "tamer" ? "howl" : cls === "shieldbearer" ? "guard" : cls === "archer" ? "ward" : cls === "assassin" ? "ward" : "bless"; break;
    case "summon": k = cls === "tamer" ? "howl" : "summon"; break;
  }
  if (cls === "tamer" && kind === "tgt" && v === "bolt") k = "command";
  return animInfo(k);
}
