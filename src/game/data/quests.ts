import type { ZoneId } from "../types";
import { xpFor } from "./balance";
import { buildQuests } from "./gen";

export type Objective =
  | { type: "kill"; mob: string; n: number; label: string }
  | { type: "collect"; item: string; n: number; label: string }
  | { type: "talk"; npc: string; label: string }
  | { type: "reach"; zone: ZoneId; x: number; z: number; r: number; label: string };

export interface QuestDef {
  id: string; name: string; giver: string; turnIn: string; zone: ZoneId; level: number; requires?: string;
  intro: string; progress: string; done: string; objectives: Objective[];
  reward: { xp: number; gold: number; items?: { id: string; n: number }[] };
  give?: { id: string; n: number }[];
  weekly?: boolean;
  spawn?: { mob: string; x: number; z: number; lvl: number };
}

export const QUESTS: Record<string, QuestDef> = {};
export const QUEST_ORDER: string[] = [];

function Q(
  id: string, name: string, giver: string, turnIn: string, zone: ZoneId, level: number, requires: string | undefined,
  intro: string, progress: string, done: string, objectives: Objective[], xpMul: number,
  items?: { id: string; n: number }[], give?: { id: string; n: number }[],
) {
  QUESTS[id] = {
    id, name, giver, turnIn, zone, level, requires, intro, progress, done, objectives,
    reward: { xp: Math.round(xpFor(level) * xpMul), gold: Math.round(10 + level * 9 * (xpMul * 3)), items }, give,
  };
  QUEST_ORDER.push(id);
}
const kill = (mob: string, n: number, label: string): Objective => ({ type: "kill", mob, n, label });
const col = (item: string, n: number, label: string): Objective => ({ type: "collect", item, n, label });
const talk = (npc: string, label: string): Objective => ({ type: "talk", npc, label });
const reach = (zone: ZoneId, x: number, z: number, r: number, label: string): Objective => ({ type: "reach", zone, x, z, r, label });

